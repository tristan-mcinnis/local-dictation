#[test]
fn a_clipboard_with_nothing_restorable_is_never_overwritten() {
    let restorable: ClipboardSnapshot = vec![vec![("public.utf8-plain-text".into(), b"hi".to_vec())]];
    assert!(!would_lose_clipboard(0, &Vec::new()), "an empty clipboard may take our text");
    assert!(would_lose_clipboard(1, &Vec::new()), "a lone promised or oversized item would be lost");
    assert!(!would_lose_clipboard(1, &restorable));
    assert!(!would_lose_clipboard(2, &restorable), "partial loss is logged per flavour, not refused");
}

#[test]
fn the_selection_probe_reads_once_the_copy_lands_and_stops_at_the_deadline() {
    use std::cell::Cell;
    let reads = Cell::new(0);
    let landed = wait_for_change_count(
        Some(7),
        || { reads.set(reads.get() + 1); Some(if reads.get() >= 3 { 8 } else { 7 }) },
        Duration::from_secs(5),
        Duration::from_millis(1),
    );
    assert_eq!(landed, Some(8), "returns the count the copy produced");
    assert_eq!(reads.get(), 3, "stops polling as soon as it moves");

    let started = Instant::now();
    let unchanged = wait_for_change_count(Some(7), || Some(7), Duration::from_millis(30), Duration::from_millis(5));
    assert_eq!(unchanged, Some(7));
    if crate::timing_checks() {
        assert!(started.elapsed() < Duration::from_secs(1), "bounded by the deadline");
    }

    assert_eq!(wait_for_change_count(None, || None, Duration::from_millis(5), Duration::from_millis(1)), None);
}

#[test]
fn the_probe_restores_after_a_double_write_of_the_same_selection() {
    // Regression: an app that writes one copy twice moved the count after
    // the read, and the user's clipboard was left holding the selection.
    assert!(probe_may_restore(Some(8), Some(9), "selected", || "selected".into()));
    assert!(
        !probe_may_restore(Some(8), Some(9), "selected", || "the user's new copy".into()),
        "a different write after the read is the user's: leave it"
    );
    assert!(probe_may_restore(Some(8), Some(8), "selected", || panic!("no read when the count held")));
}

#[test]
fn a_late_write_after_the_probe_read_blocks_the_restore() {
    // The copy landed at 8. A slow app's second write (9) arrives before
    // the restore: the restore must stand down rather than replace it.
    assert!(user_copied_during_settle(Some(8), Some(9)));
    assert!(!user_copied_during_settle(Some(8), Some(8)));
}

#[test]
fn failed_pre_delivery_steps_restore_once_and_success_never_rolls_back() {
    use std::cell::Cell;
    for failed_step in [0, 1] {
        let restored = Cell::new(0);
        let result = rollback_on_error(|| -> Result<(), &'static str> {
            if failed_step == 0 { return Err("write refused"); }
            Err("key allocation refused")
        }, || restored.set(restored.get() + 1));
        assert!(result.is_err());
        assert_eq!(restored.get(), 1);
    }
    let restored = Cell::new(false);
    let success = rollback_on_error(|| Ok::<_, ()>(()), || restored.set(true));
    assert!(success.is_ok());
    assert!(!restored.get());
}

#[test]
fn scaled_settle_scales_with_length_and_caps() {
    // Base with no extra content.
    assert_eq!(scaled_paste_settle_ms(0), PASTE_SETTLE_BASE_MS);
    // +1 ms per ~3 chars.
    assert_eq!(scaled_paste_settle_ms(3), PASTE_SETTLE_BASE_MS + 1);
    assert_eq!(scaled_paste_settle_ms(300), PASTE_SETTLE_BASE_MS + 100);
    // Clamps to the max so a long dictation can't stall the hot path.
    assert_eq!(scaled_paste_settle_ms(3_000), PASTE_SETTLE_MAX_MS);
    assert!(scaled_paste_settle_ms(3_000) <= PASTE_SETTLE_MAX_MS);
}

#[test]
fn user_copy_during_settle_is_detected_only_on_change_count_advance() {
    // Same count (our own write) → no user copy → we may restore.
    assert!(!user_copied_during_settle(Some(1), Some(1)));
    // Count advanced → someone (user) copied → don't clobber.
    assert!(user_copied_during_settle(Some(1), Some(2)));
    // Unreadable count either side → fall back to restoring (old behaviour).
    assert!(!user_copied_during_settle(None, Some(2)));
    assert!(!user_copied_during_settle(Some(1), None));
    assert!(!user_copied_during_settle(None, None));
}

